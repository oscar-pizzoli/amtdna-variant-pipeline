class PreprocessingEngine:
    """Manages AdapterRemoval execution, output locating, and post-trimming QC metrics."""

    @classmethod
    def run_adapterremoval(
        cls,
        sample: SampleRecord,
        output_dir: Path,
        log_dir: Path,
        min_read_length: int = 30,
        min_merge_overlap: int = 11,
        collapse_reads: bool = True,
        trim_ns: bool = True,
        threads: int = 4,
        integrity_mode: str = "fast",
    ) -> None:
        """Executes AdapterRemoval on the sample input files."""
        s_id = sample.sample_id
        is_paired = sample.inputs.is_paired
        r1_path = sample.inputs.r1_path
        r2_path = sample.inputs.r2_path

        output_dir.mkdir(parents=True, exist_ok=True)
        log_dir.mkdir(parents=True, exist_ok=True)

        base_prefix = output_dir / s_id
        settings_file = output_dir / f"{s_id}.settings"
        log_file = log_dir / f"{s_id}.adapterremoval.log"

        qbase, qmax, qname = FastqValidator.detect_quality_encoding(r1_path)
        logger.info(f"[{r1_path.name}] Quality Encoding Detected: {qname} => qualitybase={qbase}, qualitymax={qmax}")

        cmd = [
            "AdapterRemoval",
            "--file1", str(r1_path),
            "--basename", str(base_prefix),
            "--settings", str(settings_file),
            "--minlength", str(min_read_length),
            "--qualitybase", str(qbase),
            "--qualitymax", str(qmax),
            "--threads", str(threads),
            "--gzip",
        ]

        if is_paired and r2_path:
            cmd.extend(["--file2", str(r2_path)])
            if collapse_reads:
                cmd.extend(["--collapse", "--minalignmentlength", str(min_merge_overlap)])
        else:
            if collapse_reads:
                cmd.append("--collapse")

        if trim_ns:
            cmd.append("--trimns")

        logger.info(
            f"[{s_id}] Executing AdapterRemoval | min_length={min_read_length}, "
            f"collapse={collapse_reads}, trim_ns={trim_ns}, threads={threads}"
        )

        expected_size = sample.inputs.total_raw_bytes // 2
        # Fixed output file checks using base_prefix
        check_files = [
            Path(f"{base_prefix}.truncated.gz"),
            Path(f"{base_prefix}.collapsed.gz"),
            Path(f"{base_prefix}.pair1.truncated.gz"),
            Path(f"{base_prefix}.pair2.truncated.gz"),
        ]

        run_tracked_subprocess(
            cmd=cmd,
            task_name=f"Trimming [{s_id}]",
            output_log_file=log_file,
            expected_duration_sec=30.0,
            target_bytes=expected_size,
            check_output_files=check_files,
            check=True,
        )

        processed, warnings, errors = cls._locate_and_verify_outputs(
            base_prefix=base_prefix,
            is_paired=is_paired,
            collapse_reads=collapse_reads,
            run_started_ts=0.0,
            integrity_mode=integrity_mode,
        )

        sample.processed_reads = processed
        sample.validation.status = ValidationStatus.PASS if not errors else ValidationStatus.FAIL
        sample.validation.warnings.extend(warnings)
        sample.validation.errors.extend(errors)

        if settings_file.is_file():
            sample.metrics = cls.parse_adapterremoval_settings(
                settings_file=settings_file,
                is_paired=is_paired,
                warnings_list=sample.validation.warnings,
            )
            active_outs = [
                f for f in [
                    processed.merged_fastq,
                    processed.paired_r1_fastq,
                    processed.paired_r2_fastq,
                    processed.singleton_fastq,
                ]
                if f and f.is_file()
            ]
            gc_p, q20, q30, s_len = cls.compute_post_trimming_qc(
                active_outs, quality_base=qbase, sample_reads=25000
            )
            sample.metrics.gc_content_pct = gc_p
            sample.metrics.q20_rate_post = q20
            sample.metrics.q30_rate_post = q30
            if sample.metrics.mean_read_length_post is None:
                sample.metrics.mean_read_length_post = s_len

    @classmethod
    def _locate_and_verify_outputs(
        cls,
        base_prefix: Path,
        is_paired: bool,
        collapse_reads: bool,
        run_started_ts: float = 0.0,
        integrity_mode: str = "fast",
    ) -> Tuple[ProcessedReads, List[str], List[str]]:
        warnings: List[str] = []
        errors: List[str] = []

        pref = str(base_prefix)
        parent_dir = base_prefix.parent

        def find_file(suffix: str) -> Optional[Path]:
            c1 = Path(f"{pref}.{suffix}.gz")
            if c1.is_file():
                return c1
            c2 = Path(f"{pref}.{suffix}")
            if c2.is_file():
                return c2
            return None

        collapsed_f = find_file("collapsed")
        pair1_f = find_file("pair1.truncated")
        pair2_f = find_file("pair2.truncated")
        singleton_f = find_file("singleton.truncated")
        truncated_f = find_file("truncated")

        if not is_paired and truncated_f and not collapsed_f:
            collapsed_f = truncated_f

        has_collapsed = collapsed_f is not None and collapsed_f.stat().st_size > 0
        has_paired = (
            pair1_f is not None
            and pair2_f is not None
            and pair1_f.stat().st_size > 0
            and pair2_f.stat().st_size > 0
        )
        has_singleton = singleton_f is not None and singleton_f.stat().st_size > 0

        if has_collapsed and has_paired:
            profile = OutputProfile.COLLAPSED_AND_PAIRED
        elif has_collapsed:
            profile = OutputProfile.COLLAPSED_ONLY
        elif has_paired:
            profile = OutputProfile.PAIRED_ONLY
        elif has_singleton:
            profile = OutputProfile.SINGLETON_ONLY
        elif truncated_f and truncated_f.stat().st_size > 0:
            profile = OutputProfile.UNPAIRED_ONLY
        else:
            profile = OutputProfile.EMPTY
            errors.append(f"AdapterRemoval emitted no surviving reads for {base_prefix.name}")

        processed = ProcessedReads(
            output_profile=profile,
            collapsed_fastq=collapsed_f,
            pair1_fastq=pair1_f,
            pair2_fastq=pair2_f,
            singleton_fastq=singleton_f,
            merged_fastq=collapsed_f,
            paired_r1_fastq=pair1_f,
            paired_r2_fastq=pair2_f,
        )

        return processed, warnings, errors

    @classmethod
    def parse_adapterremoval_settings(
        cls,
        settings_file: Path,
        is_paired: bool,
        warnings_list: Optional[List[str]] = None,
    ) -> PreprocessingMetrics:
        """Parses the AdapterRemoval .settings text file to extract read counts and trimming metrics."""
        m = PreprocessingMetrics()
        if not settings_file.is_file():
            return m

        with open(settings_file, "r", encoding="utf-8") as f:
            content = f.read()

        total_m = re.search(r"Total number of (?:read pairs|reads):\s*(\d+)", content)
        if total_m:
            m.raw_total_reads = int(total_m.group(1))

        retained_m = re.search(r"Number of retained (?:reads|read pairs):\s*(\d+)", content)
        if retained_m:
            m.surviving_original_reads = int(retained_m.group(1))

        merged_m = re.search(r"Number of (?:collapsed|merged) reads:\s*(\d+)", content)
        if merged_m:
            m.merged_reads = int(merged_m.group(1))
            if m.raw_total_reads > 0:
                m.merged_fraction_raw = m.merged_reads / m.raw_total_reads

        discarded_m = re.search(r"Number of discarded (?:reads|read pairs):\s*(\d+)", content)
        if discarded_m:
            m.discarded_reads = int(discarded_m.group(1))

        adapter_m = re.search(r"Number of (?:reads|read pairs) with adapter:\s*(\d+)", content)
        if adapter_m and m.raw_total_reads > 0:
            m.adapter_trimmed_reads_pct = (int(adapter_m.group(1)) / m.raw_total_reads) * 100.0

        len_pre_m = re.search(r"Average length before trimming:\s*([\d.]+)", content)
        if len_pre_m:
            m.mean_read_length_pre = float(len_pre_m.group(1))

        len_post_m = re.search(r"Average length after trimming:\s*([\d.]+)", content)
        if len_post_m:
            m.mean_read_length_post = float(len_post_m.group(1))

        return m

    @classmethod
    def compute_post_trimming_qc(
        cls,
        fastq_files: List[Path],
        quality_base: int = 33,
        sample_reads: int = 25000,
    ) -> Tuple[float, float, float, float]:
        """Calculates GC content percentage, Q20 rate, Q30 rate, and mean read length."""
        total_bases = 0
        gc_bases = 0
        q20_bases = 0
        q30_bases = 0
        total_reads = 0

        for fpath in fastq_files:
            if not fpath or not fpath.is_file():
                continue

            opener = gzip.open if str(fpath).lower().endswith(".gz") else open
            with opener(fpath, "rt", encoding="ascii", errors="replace") as f:
                for line_idx, line in enumerate(f):
                    mod = line_idx % 4
                    if mod == 1:
                        seq = line.strip().upper()
                        total_reads += 1
                        total_bases += len(seq)
                        gc_bases += seq.count("G") + seq.count("C")
                    elif mod == 3:
                        qual = line.strip()
                        for ch in qual:
                            phred = ord(ch) - quality_base
                            if phred >= 20:
                                q20_bases += 1
                            if phred >= 30:
                                q30_bases += 1
                    if total_reads >= sample_reads:
                        break

        if total_bases == 0:
            return 0.0, 0.0, 0.0, 0.0

        gc_pct = (gc_bases / total_bases) * 100.0
        q20_pct = (q20_bases / total_bases) * 100.0
        q30_pct = (q30_bases / total_bases) * 100.0
        mean_len = total_bases / total_reads if total_reads > 0 else 0.0

        return round(gc_pct, 2), round(q20_pct, 4), round(q30_pct, 4), round(mean_len, 1)

    @classmethod
    def process_sample(
        cls,
        sample: SampleRecord,
        config: Union[Dict[str, Any], PipelineConfig],
    ) -> SampleRecord:
        """Top-level sample processor executing trimming and metrics extraction."""
        cfg_dict = config.raw_data if isinstance(config, PipelineConfig) else config
        prep_cfg = cfg_dict.get("preprocessing", {})
        res_cfg = cfg_dict.get("resources", {})
        out_cfg = cfg_dict.get("output", {})
        integ_cfg = cfg_dict.get("integrity", {})

        s_id = sample.sample_id
        op_files_dir = Path(out_cfg.get("operational_files_dir", "operational_files"))
        sample_out = op_files_dir / "alignment" / s_id / "trimmed"
        log_dir = op_files_dir / "logs" / "preprocessing"

        min_len = int(prep_cfg.get("min_read_length", 30))
        min_overlap = int(prep_cfg.get("min_merge_overlap", 11))
        collapse = bool(prep_cfg.get("collapse_reads", True))
        trim_ns = bool(prep_cfg.get("trim_ns", True))
        threads = int(res_cfg.get("threads", 4))
        integ_mode = str(integ_cfg.get("mode", "fast"))

        cls.run_adapterremoval(
            sample=sample,
            output_dir=sample_out,
            log_dir=log_dir,
            min_read_length=min_len,
            min_merge_overlap=min_overlap,
            collapse_reads=collapse,
            trim_ns=trim_ns,
            threads=threads,
            integrity_mode=integ_mode,
        )

        return sample


class PreprocessingOrchestrator:
    """Orchestrates FASTQ ingestion, validation, and adapter trimming/merging via PreprocessingEngine."""

    @classmethod
    def run_sample(
        cls,
        sample_input: RawSampleInput,
        output_dir: Path,
        log_dir: Path,
        min_length: int = 30,
        min_overlap: int = 11,
        collapse_reads: bool = True,
        trim_ns: bool = True,
        threads: int = 4,
        integrity_mode: str = "fast",
    ) -> SampleRecord:
        """Executes full sample preprocessing, metrics extraction, and output verification."""
        sample_id = sample_input.sample_id
        is_paired = sample_input.r2_path is not None

        sample_record = SampleRecord(
            sample_id=sample_id,
            identity=SampleIdentity(
                sample_id=sample_id,
                library_id=sample_input.library_id or f"LIB_{sample_id}",
                is_paired=is_paired,
            ),
            inputs=InputFiles(
                data_type=DataType.FASTQ,
                is_paired=is_paired,
                r1_path=Path(sample_input.r1_path).resolve(),
                r2_path=Path(sample_input.r2_path).resolve() if is_paired else None,
            ),
            validation=ValidationResult(status=ValidationStatus.UNTESTED),
        )

        sample_out = output_dir / sample_id
        sample_log = log_dir / sample_id

        PreprocessingEngine.run_adapterremoval(
            sample=sample_record,
            output_dir=sample_out,
            log_dir=sample_log,
            min_read_length=min_length,
            min_merge_overlap=min_overlap,
            collapse_reads=collapse_reads,
            trim_ns=trim_ns,
            threads=threads,
            integrity_mode=integrity_mode,
        )

        return sample_record


