class FilenameTokenizer:
    """Tokenizes sequencing filenames to reliably extract sample ID, lane, mate, and extension."""

    FASTQ_EXTENSIONS = (
        ".fastq.gz",
        ".fq.gz",
        ".fastq",
        ".fq",
    )

    BAM_EXTENSIONS = (
        ".bam",
    )

    R1_PATTERNS = [
        re.compile(r"[_.-]R1(?:[_.-]|\.|$)", re.IGNORECASE),
        re.compile(r"[_.-]1(?:[_.-]|\.|$)", re.IGNORECASE),
        re.compile(r"_read1_", re.IGNORECASE),
    ]

    R2_PATTERNS = [
        re.compile(r"[_.-]R2(?:[_.-]|\.|$)", re.IGNORECASE),
        re.compile(r"[_.-]2(?:[_.-]|\.|$)", re.IGNORECASE),
        re.compile(r"_read2_", re.IGNORECASE),
    ]

    LANE_PATTERN = re.compile(r"_(L\d{3})_", re.IGNORECASE)

    @classmethod
    def tokenize(cls, file_path: Path) -> DiscoveredFile:
        """Parses filename metadata into a DiscoveredFile object."""
        name = file_path.name

        ext = ""
        for known_ext in sorted(cls.FASTQ_EXTENSIONS + cls.BAM_EXTENSIONS, key=len, reverse=True):
            if name.lower().endswith(known_ext):
                ext = known_ext
                break

        stem = name[:-len(ext)] if ext else file_path.stem
        is_compressed = name.lower().endswith(".gz")

        lane_match = cls.LANE_PATTERN.search(name)
        lane = lane_match.group(1).upper() if lane_match else "L001"

        mate = None
        for pat in cls.R1_PATTERNS:
            if pat.search(name):
                mate = "R1"
                break
        if mate is None:
            for pat in cls.R2_PATTERNS:
                if pat.search(name):
                    mate = "R2"
                    break

        clean_id = stem
        clean_id = re.sub(r"_(L\d{3})_", "_", clean_id, flags=re.IGNORECASE)
        clean_id = re.sub(r"[_.-]R[12](?:[_.-]|$)", "", clean_id, flags=re.IGNORECASE)
        clean_id = re.sub(r"[_.-][12](?:[_.-]|$)", "", clean_id, flags=re.IGNORECASE)
        clean_id = re.sub(r"_001$", "", clean_id, flags=re.IGNORECASE)
        clean_id = clean_id.rstrip("._-")

        size_bytes = file_path.stat().st_size if file_path.is_file() else 0

        return DiscoveredFile(
            path=file_path.resolve(),
            sample_id=clean_id,
            lane=lane,
            mate=mate,
            extension=ext,
            is_compressed=is_compressed,
            file_size_bytes=size_bytes,
        )


class IntegrityEngine:
    """Validates physical file integrity, checking magic bytes, headers, and truncation."""

    GZIP_MAGIC = b"\x1f\x8b"
    BAM_MAGIC = b"BAM\x01"

    @classmethod
    def verify_file(cls, path: Path) -> Tuple[bool, Optional[str]]:
        """Checks magic bytes and file readability."""
        if not path.is_file():
            return False, f"File does not exist: {path}"

        size = path.stat().st_size
        if size == 0:
            return False, f"File is completely empty (0 bytes): {path}"

        try:
            with open(path, "rb") as f:
                header = f.read(4)

            name = path.name.lower()
            if name.endswith(".gz"):
                if not header.startswith(cls.GZIP_MAGIC):
                    return False, f"Corrupted GZIP header in {path.name}"
            elif name.endswith(".bam"):
                if header.startswith(cls.GZIP_MAGIC):
                    pass
                elif not header.startswith(cls.BAM_MAGIC):
                    return False, f"Corrupted BAM header in {path.name}"

            return True, None
        except Exception as exc:
            return False, f"I/O error reading {path.name}: {exc}"


class FastqValidator:
    """Validates FASTQ integrity, record structure, and detects quality score encoding."""

    @classmethod
    def detect_quality_encoding(cls, fastq_path: Path, sample_reads: int = 10000) -> Tuple[int, int, str]:
        """
        Samples FASTQ quality scores to detect Sanger/Illumina 1.8+ (Phred+33) vs Illumina 1.3+ (Phred+64).
        Returns (qualitybase, qualitymax, name).
        """
        min_ascii = 126
        max_ascii = 0
        reads_sampled = 0

        opener = gzip.open if str(fastq_path).lower().endswith(".gz") else open

        with opener(fastq_path, "rt", encoding="ascii", errors="replace") as f:
            for line_idx, line in enumerate(f):
                if line_idx % 4 == 3:
                    qual = line.strip()
                    reads_sampled += 1
                    for ch in qual:
                        val = ord(ch)
                        if val < min_ascii:
                            min_ascii = val
                        if val > max_ascii:
                            max_ascii = val
                    if reads_sampled >= sample_reads:
                        break

        if reads_sampled == 0:
            return 33, 93, "Sanger / Illumina 1.8+ (Phred+33) [Default]"

        if min_ascii < 64:
            return 33, 93, f"Sanger / Illumina 1.8+ (Phred+33) (ASCII: {min_ascii} ['{chr(min_ascii)}'] -> {max_ascii} ['{chr(max_ascii)}'])"
        else:
            return 64, 104, f"Illumina 1.3+ / 1.5+ (Phred+64) (ASCII: {min_ascii} ['{chr(min_ascii)}'] -> {max_ascii} ['{chr(max_ascii)}'])"


class BAMValidationEngine:
    """Validates BAM headers, coordinate sorting, and indexation."""

    @classmethod
    def validate_bam(cls, bam_path: Path) -> Tuple[bool, List[str], List[str]]:
        warnings: List[str] = []
        errors: List[str] = []

        if not bam_path.is_file():
            return False, warnings, [f"BAM file not found: {bam_path}"]

        try:
            with pysam.AlignmentFile(str(bam_path), "rb") as sam:
                header = sam.header.to_dict()
                if "HD" not in header or header["HD"].get("SO") != "coordinate":
                    warnings.append(f"BAM {bam_path.name} is not marked as coordinate-sorted in @HD header.")
        except Exception as exc:
            errors.append(f"Failed to parse BAM {bam_path.name}: {exc}")
            return False, warnings, errors

        return len(errors) == 0, warnings, errors


class SampleDiscoveryEngine:
    """Discovers and structures raw samples from an input directory."""

    @classmethod
    def build_sample_records(
        cls,
        input_dir: Path,
        config: Optional[Union[Dict[str, Any], PipelineConfig]] = None,
        integrity_mode: str = "fast",
    ) -> List[SampleRecord]:
        """Discovers raw FASTQ or BAM files and constructs validated SampleRecord objects."""
        input_p = Path(input_dir).resolve()
        if not input_p.is_dir():
            raise FileNotFoundError(f"Input directory does not exist: {input_p}")

        cfg_dict = config.raw_data if isinstance(config, PipelineConfig) else (config or {})
        input_cfg = cfg_dict.get("input", {})
        data_type_str = str(input_cfg.get("data_type", "FASTQ")).upper()

        discovered: List[DiscoveredFile] = []
        for root, _, files in os.walk(input_p):
            for fname in files:
                fpath = Path(root) / fname
                if fname.startswith("."):
                    continue
                if data_type_str == "BAM":
                    if fname.lower().endswith(".bam") and not fname.lower().endswith(".bai"):
                        discovered.append(FilenameTokenizer.tokenize(fpath))
                else:
                    for ext in FilenameTokenizer.FASTQ_EXTENSIONS:
                        if fname.lower().endswith(ext):
                            discovered.append(FilenameTokenizer.tokenize(fpath))
                            break

        if not discovered:
            logger.warning(f"No matching {data_type_str} files found in {input_p}")
            return []

        logger.info(f"Discovered {len(discovered)} raw file(s) in {input_p.name}")

        samples_by_id: Dict[str, List[DiscoveredFile]] = {}
        for df in discovered:
            samples_by_id.setdefault(df.sample_id, []).append(df)

        sample_records: List[SampleRecord] = []

        print("\n" + "-" * 85)
        print(" PRE-FLIGHT SAMPLE DISCOVERY REPORT")
        print("-" * 85)
        print(f"{'SAMPLE ID':<18} | {'TYPE':<6} | {'LAYOUT':<6} | {'LANES':<6} | {'STATUS':<8} | NOTES")
        print("-" * 85)

        for s_id, flist in sorted(samples_by_id.items()):
            is_paired = any(f.mate == "R2" for f in flist)
            layout_str = "PE" if is_paired else "SE"
            r1_f = next((f.path for f in flist if f.mate == "R1"), flist[0].path)
            r2_f = next((f.path for f in flist if f.mate == "R2"), None) if is_paired else None

            valid_ok, valid_err = IntegrityEngine.verify_file(r1_f)
            if valid_ok and r2_f:
                valid_ok, valid_err = IntegrityEngine.verify_file(r2_f)

            stat = ValidationStatus.PASS if valid_ok else ValidationStatus.FAIL
            notes = "Ready for preprocessing" if valid_ok else (valid_err or "Integrity check failed")

            print(f"{s_id:<18} | {data_type_str:<6} | {layout_str:<6} | {len(flist):<6} | {stat.value:<8} | {notes}")

            rec = SampleRecord(
                sample_id=s_id,
                identity=SampleIdentity(
                    sample_id=s_id,
                    library_id=f"LIB_{s_id}",
                    data_type=DataType(data_type_str),
                    is_paired=is_paired,
                ),
                inputs=InputFiles(
                    data_type=DataType(data_type_str),
                    is_paired=is_paired,
                    raw_files=flist,
                    r1_path=r1_f,
                    r2_path=r2_f,
                    total_raw_bytes=sum(f.file_size_bytes for f in flist),
                ),
                validation=ValidationResult(status=stat, errors=[valid_err] if valid_err else []),
            )
            sample_records.append(rec)

        print("-" * 85 + "\n")
        logger.info("Pre-Flight Discovery Report generated.")
        return sample_records


