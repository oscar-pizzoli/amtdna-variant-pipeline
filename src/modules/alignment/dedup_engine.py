"""PCR duplication identification and handling engine: samtools markdup execution, Dual-BAM generation, verification, and metrics parsing."""

from dataclasses import dataclass, field
import logging
import os
from pathlib import Path
import re
import shutil
import subprocess
from typing import Any, Dict, List, Optional, Tuple, Union

import pysam

from src.modules.alignment.models import DedupMetrics, DedupMode

logger = logging.getLogger("mtDNA_Pipeline.DedupEngine")


class DedupEngineError(Exception):
    """Raised when deduplication execution, verification, or parsing fails."""
    pass


@dataclass
class DedupExecutionResult:
    """Outcome and artifacts resulting from duplicate marking and physical deduplication."""

    sample_id: str
    markdup_bam: Optional[Path] = None          # BAM with 0x400 flag set
    markdup_bai: Optional[Path] = None
    dedup_bam: Optional[Path] = None            # BAM with duplicate records physically removed
    dedup_bai: Optional[Path] = None
    markdup_metrics_txt: Optional[Path] = None  # Preserved text report generated by markdup
    metrics: Optional[DedupMetrics] = None      # Parsed metrics (None if unparseable/unavailable)
    is_empty: bool = False                      # True if BAM is structurally valid but contains 0 reads
    command_lines: List[str] = field(default_factory=list)
    is_successful: bool = False
    error_message: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Serializes deduplication outcome."""
        return {
            "sample_id": self.sample_id,
            "markdup_bam": str(self.markdup_bam) if self.markdup_bam else None,
            "markdup_bai": str(self.markdup_bai) if self.markdup_bai else None,
            "dedup_bam": str(self.dedup_bam) if self.dedup_bam else None,
            "dedup_bai": str(self.dedup_bai) if self.dedup_bai else None,
            "markdup_metrics_txt": str(self.markdup_metrics_txt) if self.markdup_metrics_txt else None,
            "metrics": self.metrics.to_dict() if self.metrics else None,
            "is_empty": self.is_empty,
            "command_lines": self.command_lines,
            "is_successful": self.is_successful,
            "error_message": self.error_message,
        }


class DedupEngine:
    """Manages samtools markdup execution, dual-BAM generation (.markdup vs .dedup), indexing, and metrics parsing."""

    @classmethod
    def index_bam(cls, bam_path: Path, threads: int = 2, use_csi: bool = False) -> Path:
        """Generates coordinate index (.bai or .csi) for a target BAM file."""
        if not shutil.which("samtools"):
            raise DedupEngineError("Cannot index BAM: 'samtools' executable not found in PATH.")

        bam = Path(bam_path).resolve()
        if not bam.is_file() or bam.stat().st_size == 0:
            raise DedupEngineError(f"Cannot index missing or empty BAM: {bam.name}")

        cmd = ["samtools", "index", "-@", str(max(1, threads))]
        if use_csi:
            cmd.append("-c")
        cmd.append(str(bam))

        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if res.returncode != 0:
            raise DedupEngineError(
                f"Failed to generate index for {bam.name} (exit code {res.returncode}): {res.stderr.strip()}"
            )

        # Detect generated index file (.bai, .bam.bai, or .csi)
        expected_indices = [
            bam.with_name(bam.name + (".csi" if use_csi else ".bai")),
            bam.with_suffix(".csi" if use_csi else ".bai"),
        ]

        for idx_path in expected_indices:
            if idx_path.is_file() and idx_path.stat().st_size > 0:
                try:
                    bam_mtime = bam.stat().st_mtime
                    if idx_path.stat().st_mtime <= bam_mtime:
                        target_time = bam_mtime + 2.0
                        os.utime(idx_path, (target_time, target_time))
                except OSError:
                    pass
                return idx_path

        raise DedupEngineError(f"Index generation completed but output index file was not found for {bam.name}")

    @classmethod
    def verify_bam_integrity(cls, bam_path: Path) -> Tuple[bool, int]:
        """Performs quickcheck integrity validation and returns (is_empty, record_count).

        Returns:
            Tuple of (is_empty: bool, record_count: int).
        """
        if not bam_path.is_file() or bam_path.stat().st_size == 0:
            raise DedupEngineError(f"BAM file is physically missing or empty on disk: {bam_path.name}")

        # 1. Fast truncation and header check with samtools quickcheck
        if shutil.which("samtools"):
            res_qc = subprocess.run(
                ["samtools", "quickcheck", "-v", str(bam_path)],
                capture_output=True,
                text=True,
                check=False,
            )
            if res_qc.returncode != 0:
                raise DedupEngineError(
                    f"Integrity check failed ('samtools quickcheck' code {res_qc.returncode}) for {bam_path.name}: {res_qc.stderr.strip()}"
                )

        # 2. Check header validity and count total records
        try:
            with pysam.AlignmentFile(str(bam_path), "rb", check_sq=False) as bam_f:
                if not bam_f.header:
                    raise DedupEngineError(f"Header missing or corrupted in {bam_path.name}")
                record_count = bam_f.count(until_eof=True)
        except DedupEngineError:
            raise
        except Exception as exc:
            raise DedupEngineError(f"Corrupted BAM file structure in {bam_path.name}: {exc}") from exc

        is_empty = record_count == 0
        return is_empty, record_count

    @classmethod
    def verify_dedup_bam(cls, dedup_bam: Path, markdup_record_count: int) -> int:
        """Validates that deduplicated BAM has <= records than markdup BAM and contains zero 0x400 duplicate flags."""
        is_empty, dedup_records = cls.verify_bam_integrity(dedup_bam)

        if dedup_records > markdup_record_count:
            raise DedupEngineError(
                f"Deduplicated BAM {dedup_bam.name} contains more records ({dedup_records:,}) "
                f"than input markdup BAM ({markdup_record_count:,})."
            )

        # Scan to verify absence of 0x400 duplicate flags
        try:
            with pysam.AlignmentFile(str(dedup_bam), "rb", check_sq=False) as bam_f:
                for read in bam_f.fetch(until_eof=True):
                    if read.is_duplicate:
                        raise DedupEngineError(
                            f"Record '{read.query_name}' in {dedup_bam.name} retains duplicate flag 0x400."
                        )
        except DedupEngineError:
            raise
        except Exception as exc:
            raise DedupEngineError(f"Error scanning duplicate flags in {dedup_bam.name}: {exc}") from exc

        return dedup_records

    @classmethod
    def parse_markdup_stats(cls, stats_content_or_file: Union[Path, str]) -> Optional[DedupMetrics]:
        """Parses key-value statistical metrics generated by 'samtools markdup -s / -f'.

        Args:
            stats_content_or_file: Path to the markdup statistics text file or raw string content.

        Returns:
            Populated DedupMetrics container, or None if the input is unparseable or lacks required metrics.
        """
        text = ""
        if isinstance(stats_content_or_file, Path):
            if not stats_content_or_file.is_file():
                logger.warning(f"Markdup stats file not found: {stats_content_or_file}")
                return None
            try:
                text = stats_content_or_file.read_text(encoding="utf-8")
            except OSError as exc:
                logger.warning(f"Could not read markdup stats file {stats_content_or_file}: {exc}")
                return None
        elif isinstance(stats_content_or_file, str):
            text = stats_content_or_file

        if not text.strip():
            logger.warning("Empty markdup stats content provided for parsing.")
            return None

        # Extract key-value pairs (e.g., 'EXAMINED: 1000', 'DUPLICATE PAIR: 50')
        kv_pairs: Dict[str, int] = {}
        for line in text.splitlines():
            clean_line = line.strip()
            if not clean_line or clean_line.startswith("#"):
                continue
            if ":" in clean_line:
                parts = clean_line.split(":", 1)
                key = parts[0].strip().upper()
                val_str = parts[1].strip()
                match = re.search(r"^(\d+)", val_str)
                if match:
                    kv_pairs[key] = int(match.group(1))

        # Check required fields
        examined_reads = kv_pairs.get("EXAMINED", kv_pairs.get("READ", None))
        if examined_reads is None:
            logger.warning(f"Could not find 'EXAMINED' or 'READ' in markdup stats:\n{text}")
            return None

        paired_reads_examined = kv_pairs.get("PAIRED", 0)
        single_reads_examined = kv_pairs.get("SINGLE", 0)

        # In samtools markdup, 'DUPLICATE PAIR' refers to the count of duplicate pairs
        duplicate_pairs = kv_pairs.get("DUPLICATE PAIR", kv_pairs.get("DUPLICATE PAIRS", 0))
        duplicate_single = kv_pairs.get("DUPLICATE SINGLE", kv_pairs.get("DUPLICATE SINGLETON", 0))
        duplicate_total = kv_pairs.get("DUPLICATE TOTAL", kv_pairs.get("DUPLICATES", None))

        # If DUPLICATE TOTAL is not directly given, compute exact read count: (pairs * 2) + single
        if duplicate_total is None:
            duplicate_total = (duplicate_pairs * 2) + duplicate_single

        # Derived pair counts and fractions
        examined_pairs = paired_reads_examined // 2 if paired_reads_examined > 0 else 0
        retained_reads = max(0, examined_reads - duplicate_total)
        retained_pairs = max(0, examined_pairs - duplicate_pairs)
        retained_single = max(0, single_reads_examined - duplicate_single)

        dup_fraction_reads = duplicate_total / examined_reads if examined_reads > 0 else 0.0
        dup_fraction_pairs = duplicate_pairs / examined_pairs if examined_pairs > 0 else 0.0

        return DedupMetrics(
            examined_reads=examined_reads,
            examined_pairs=examined_pairs,
            examined_single_fragments=single_reads_examined,
            duplicate_reads=duplicate_total,
            duplicate_pairs=duplicate_pairs,
            duplicate_single_fragments=duplicate_single,
            retained_reads=retained_reads,
            retained_pairs=retained_pairs,
            retained_single_fragments=retained_single,
            duplication_rate_reads=dup_fraction_reads,
            duplication_rate_pairs=dup_fraction_pairs,
        )

    @classmethod
    def execute_dedup(
        cls,
        sample_id: str,
        input_sorted_bam: Path,
        output_dir: Path,
        log_dir: Path,
        dedup_mode: DedupMode = DedupMode.BOTH,
        threads: int = 4,
        use_csi: bool = False,
        cleanup_on_failure: bool = True,
    ) -> DedupExecutionResult:
        """Executes 'samtools markdup -s' to flag duplicates and produces dual BAM outputs (.markdup and/or .dedup).

        Args:
            sample_id: Unique sample identifier.
            input_sorted_bam: Path to the fixmate-synchronized, coordinate-sorted BAM.
            output_dir: Target output directory for marked and deduplicated BAM files.
            log_dir: Output folder for stderr/stdout logs.
            dedup_mode: Strategy (DedupMode.MARK, DedupMode.REMOVE, or DedupMode.BOTH).
            threads: Number of CPU threads allocated for compression/decompression.
            use_csi: If True, generates .csi indices instead of standard .bai indices.
            cleanup_on_failure: If True, unlinks partial/corrupted artifacts on failure.

        Returns:
            DedupExecutionResult containing output paths, verified indices, and parsed DedupMetrics.
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        log_dir.mkdir(parents=True, exist_ok=True)

        markdup_bam = output_dir / f"{sample_id}.markdup.bam"
        markdup_bai: Optional[Path] = None
        dedup_bam = output_dir / f"{sample_id}.dedup.bam"
        dedup_bai: Optional[Path] = None
        metrics_txt = output_dir / f"{sample_id}.markdup.metrics.txt"

        markdup_err = log_dir / f"{sample_id}.samtools_markdup.err"
        filter_err = log_dir / f"{sample_id}.samtools_dedup_view.err"
        executed_cmds: List[str] = []

        logger.info(f"[{sample_id}] Executing deduplication in mode '{dedup_mode.value}' -> {markdup_bam.name}")

        try:
            # 1. Execute samtools markdup with reporting (-s and -f)
            cmd_markdup = [
                "samtools", "markdup",
                "-@", str(max(1, threads)),
                "-s",
                "-f", str(metrics_txt),
                str(input_sorted_bam),
                str(markdup_bam),
            ]
            cmd_markdup_str = " ".join(cmd_markdup)
            logger.debug(f"Executing: {cmd_markdup_str}")

            with open(markdup_err, "w", encoding="utf-8") as err_f:
                res_mark = subprocess.run(cmd_markdup, stdout=subprocess.DEVNULL, stderr=err_f, text=True, check=False)

            if res_mark.returncode != 0 or not markdup_bam.is_file() or markdup_bam.stat().st_size == 0:
                raise DedupEngineError(
                    f"'samtools markdup' failed (exit code {res_mark.returncode}). Check log: {markdup_err}"
                )
            executed_cmds.append(cmd_markdup_str)

            # 2. Verify BAM integrity and index marked BAM (.markdup.bam)
            is_empty, markdup_records = cls.verify_bam_integrity(markdup_bam)
            if is_empty:
                logger.warning(f"[{sample_id}] Markdup BAM {markdup_bam.name} is structurally valid but contains 0 reads.")

            markdup_bai = cls.index_bam(markdup_bam, threads=threads, use_csi=use_csi)
            executed_cmds.append(f"samtools index -@ {threads} {markdup_bam}")

            # 3. Parse markdup metrics
            # If -f did not write to metrics_txt, attempt fallback to markdup stderr
            metrics: Optional[DedupMetrics] = None
            if metrics_txt.is_file() and metrics_txt.stat().st_size > 0:
                metrics = cls.parse_markdup_stats(metrics_txt)
            elif markdup_err.is_file() and markdup_err.stat().st_size > 0:
                err_text = markdup_err.read_text(encoding="utf-8")
                metrics = cls.parse_markdup_stats(err_text)
                if metrics:
                    metrics_txt.write_text(err_text, encoding="utf-8")

            if metrics:
                logger.info(
                    f"[{sample_id}] Markdup parsed: {metrics.examined_reads:,} reads examined | "
                    f"{metrics.duplicate_reads:,} duplicates ({metrics.duplication_rate_reads * 100:.2f}%)"
                )
            else:
                logger.warning(f"[{sample_id}] Could not parse markdup metrics report; recording metrics as None.")

            # 4. Generate physically deduplicated BAM (.dedup.bam) if requested
            if dedup_mode in (DedupMode.BOTH, DedupMode.REMOVE):
                logger.info(f"[{sample_id}] Generating physically deduplicated BAM -> {dedup_bam.name}")
                cmd_dedup_view = [
                    "samtools", "view",
                    "-@", str(max(1, threads)),
                    "-b",
                    "-F", "0x400",  # Exclude all duplicate-flagged records
                    "-o", str(dedup_bam),
                    str(markdup_bam),
                ]
                cmd_dedup_str = " ".join(cmd_dedup_view)

                with open(filter_err, "w", encoding="utf-8") as err_f:
                    res_dedup = subprocess.run(cmd_dedup_view, stdout=subprocess.DEVNULL, stderr=err_f, check=False)

                if res_dedup.returncode != 0 or not dedup_bam.is_file() or dedup_bam.stat().st_size == 0:
                    raise DedupEngineError(
                        f"Failed to generate deduplicated BAM {dedup_bam.name} (exit code {res_dedup.returncode}). Log: {filter_err}"
                    )
                executed_cmds.append(cmd_dedup_str)

                # Rigorously verify that .dedup.bam has <= records and zero 0x400 flags
                dedup_records = cls.verify_dedup_bam(dedup_bam, markdup_record_count=markdup_records)
                dedup_bai = cls.index_bam(dedup_bam, threads=threads, use_csi=use_csi)
                executed_cmds.append(f"samtools index -@ {threads} {dedup_bam}")

                logger.info(
                    f"[{sample_id}] Deduplicated BAM verified: {dedup_records:,} / {markdup_records:,} records retained."
                )

            # 5. Handle DedupMode.REMOVE (unlink marked BAM if only clean BAM was requested)
            if dedup_mode == DedupMode.REMOVE:
                if markdup_bam.is_file():
                    markdup_bam.unlink()
                    markdup_bam = None
                if markdup_bai and markdup_bai.is_file():
                    markdup_bai.unlink()
                    markdup_bai = None

            return DedupExecutionResult(
                sample_id=sample_id,
                markdup_bam=markdup_bam,
                markdup_bai=markdup_bai,
                dedup_bam=dedup_bam if dedup_mode in (DedupMode.BOTH, DedupMode.REMOVE) else None,
                dedup_bai=dedup_bai if dedup_mode in (DedupMode.BOTH, DedupMode.REMOVE) else None,
                markdup_metrics_txt=metrics_txt if metrics_txt.is_file() else None,
                metrics=metrics,
                is_empty=is_empty,
                command_lines=executed_cmds,
                is_successful=True,
            )

        except Exception as exc:
            logger.error(f"[{sample_id}] Deduplication engine failed: {exc}")

            if cleanup_on_failure:
                for partial_file in (markdup_bam, markdup_bai, dedup_bam, dedup_bai):
                    if partial_file and partial_file.is_file():
                        try:
                            partial_file.unlink()
                        except OSError:
                            pass

            return DedupExecutionResult(
                sample_id=sample_id,
                markdup_bam=None,
                markdup_bai=None,
                dedup_bam=None,
                dedup_bai=None,
                markdup_metrics_txt=metrics_txt if (metrics_txt and metrics_txt.is_file()) else None,
                metrics=None,
                is_empty=False,
                command_lines=executed_cmds,
                is_successful=False,
                error_message=str(exc),
            )
